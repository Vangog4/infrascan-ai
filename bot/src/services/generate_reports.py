_LINE_COLOR = (220, 224, 230)


class ContractPDF(FPDF):
    def footer(self):
        self.set_y(-15)
        self.set_draw_color(*_LINE_COLOR)
        self.line(10, self.get_y(), 200, self.get_y())
        self.ln(2)
        self.set_font("dj", "", 8)
        self.set_text_color(*_MUTED)
        self.cell(0, 5, "Договор купли-продажи оборудования | ИП Гудков И.Г.", align="C")


class ActPDF(FPDF):
    def header(self):
        self.set_fill_color(*_ACCENT)
        self.rect(0, 0, 210, 8, "F")
        self.set_y(15)

    def footer(self):
        self.set_y(-15)
        self.set_draw_color(*_LINE_COLOR)
        self.line(10, self.get_y(), 200, self.get_y())
        self.ln(2)
        self.set_font("dj", "", 8)
        self.set_text_color(*_MUTED)
